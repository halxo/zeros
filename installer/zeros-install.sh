#!/usr/bin/env bash
# Zeros automatic installer. DRY RUN by default: prints every step unless --really is passed.
# Usage: zeros-install /dev/sdX [--really]
# Examples:
#   zeros-install /dev/nvme0n1          # dry run on NVMe drive
#   zeros-install /dev/sda --really     # install onto SATA SSD
set -euo pipefail

DISK=${1:?usage: $0 /dev/sdX [--really]}
GO=${2:-}
run() { echo "+ $*"; [[ $GO == --really ]] && "$@" || true; }

# Helper to determine partition device path (e.g. /dev/nvme0n1p1 vs /dev/sda1)
get_part() {
  local disk=$1 part_num=$2
  if [[ "$disk" =~ [0-9]$ ]]; then
    echo "${disk}p${part_num}"
  else
    echo "${disk}${part_num}"
  fi
}

PART_ESP=$(get_part "$DISK" 1)
PART_ROOT=$(get_part "$DISK" 2)

echo "=========================================================="
echo "  Zeros OS Installer"
echo "  Target Disk: $DISK"
echo "  ESP:         $PART_ESP"
echo "  Root:        $PART_ROOT"
[[ $GO != --really ]] && echo "  MODE:        DRY RUN (pass --really to execute)" || echo "  MODE:        REAL EXECUTION"
echo "=========================================================="

PROFILE=$(zeros-detect 2>/dev/null || python3 -m zeros.detect)
KEY=$(echo "$PROFILE" | python3 -c 'import sys,json;print(json.load(sys.stdin)["cache_key"])')
echo "Hardware build profile key: $KEY"

# 1. Partition disk with GPT
run parted -s "$DISK" mklabel gpt
run parted -s "$DISK" mkpart "ZEROS_BOOT" fat32 1MiB 513MiB
run parted -s "$DISK" set 1 esp on
run parted -s "$DISK" mkpart "zeros_root" btrfs 513MiB 100%

# 2. Format filesystems
run mkfs.fat -F32 -n "ZEROS_BOOT" "$PART_ESP"
run mkfs.btrfs -f -L "zeros_root" "$PART_ROOT"

# 3. Setup Btrfs subvolumes
MNT_SETUP="/mnt/zeros_setup"
run mkdir -p "$MNT_SETUP"
run mount "$PART_ROOT" "$MNT_SETUP"
run btrfs subvolume create "$MNT_SETUP/@"
run btrfs subvolume create "$MNT_SETUP/@home"
run btrfs subvolume create "$MNT_SETUP/@snapshots"
run umount "$MNT_SETUP"

# 4. Mount target subvolume and ESP
TARGET="/mnt/gentoo"
run mkdir -p "$TARGET"
run mount -o subvol=@,compress=zstd:3 "$PART_ROOT" "$TARGET"
run mkdir -p "$TARGET/home" "$TARGET/boot/efi"
run mount -o subvol=@home,compress=zstd:3 "$PART_ROOT" "$TARGET/home"
run mount "$PART_ESP" "$TARGET/boot/efi"

# 5. Populate base system (1: binary cache for profile, 2: live environment copy)
if [[ $GO == --really ]]; then
  echo "Fetching system base..."
  if curl -fsSL "https://github.com/halxo/zeros/releases/download/rolling-cache/cache-$KEY.tar.zst" 2>/dev/null | tar -C "$TARGET" -I zstd -x 2>/dev/null; then
    echo "Unpacked hardware-optimized binary cache ($KEY)"
  elif [ -d "/usr/share/zeros-overlay" ]; then
    echo "No remote cache found. Copying live system to target disk..."
    # rsync/cp live system excluding virtual mounts
    for d in bin sbin lib lib64 usr etc opt var root; do
      [ -d "/$d" ] && cp -a "/$d" "$TARGET/" 2>/dev/null || true
    done
    mkdir -p "$TARGET/proc" "$TARGET/sys" "$TARGET/dev" "$TARGET/run" "$TARGET/tmp"
  fi
else
  echo "+ [dry-run] Fetch cache-$KEY or replicate live environment to $TARGET"
fi

# 6. Generate tailored make.conf and fstab
run mkdir -p "$TARGET/etc/portage"
run bash -c "zeros-detect --make-conf > $TARGET/etc/portage/make.conf 2>/dev/null || python3 -m zeros.detect --make-conf > $TARGET/etc/portage/make.conf"

if [[ $GO == --really ]]; then
  ESP_UUID=$(blkid -s UUID -o value "$PART_ESP" || echo "BOOT_UUID")
  ROOT_UUID=$(blkid -s UUID -o value "$PART_ROOT" || echo "ROOT_UUID")
  cat > "$TARGET/etc/fstab" <<FSTAB
# /etc/fstab: generated by zeros-install
UUID=$ROOT_UUID  /          btrfs  subvol=@,compress=zstd:3,noatime          0 0
UUID=$ROOT_UUID  /home      btrfs  subvol=@home,compress=zstd:3,noatime      0 0
UUID=$ROOT_UUID  /.snapshots btrfs subvol=@snapshots,compress=zstd:3,noatime 0 0
UUID=$ESP_UUID   /boot/efi  vfat   defaults,noatime                          0 2
FSTAB
else
  echo "+ [dry-run] Generate /etc/fstab with Btrfs subvolumes and EFI mount"
fi

# 7. Install bootloader (UEFI with --removable for 100% motherboard compatibility + BIOS fallback)
run chroot "$TARGET" grub-install --target=x86_64-efi --efi-directory=/boot/efi --bootloader-id=zeros --removable --recheck || true
run chroot "$TARGET" grub-install --target=i386-pc --recheck "$DISK" 2>/dev/null || true
run chroot "$TARGET" grub-mkconfig -o /boot/grub/grub.cfg || true

# 8. Compile newest Linux kernel tailored to this machine
echo "Kernel build steps for newest stable Linux:"
python3 -c "from zeros import kernel; print('\n'.join(kernel.build_script(kernel.latest_stable())))" 2>/dev/null || true

echo "=========================================================="
echo "  Zeros installation process completed!"
echo "=========================================================="
