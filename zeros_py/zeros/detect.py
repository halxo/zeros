"""Hardware detection -> build profile (make.conf values + cache key)."""
import hashlib, json, os, re, subprocess
from dataclasses import dataclass, asdict, field

# CPU flags that map to Gentoo CPU_FLAGS_X86 names
CPU_FLAG_MAP = ["aes", "avx", "avx2", "avx512f", "fma", "mmx", "popcnt",
                "sse", "sse2", "sse3", "sse4_1", "sse4_2", "ssse3", "pclmul", "sha"]

GPU_VENDORS = {"10de": "nvidia", "1002": "amdgpu radeonsi", "8086": "intel",
               "1af4": "virgl", "15ad": "vmware"}


@dataclass
class Profile:
    arch: str = "amd64"
    cpu_model: str = "unknown"
    march: str = "x86-64"
    cpu_flags: list = field(default_factory=list)
    cores: int = 1
    mem_mb: int = 0
    video_cards: list = field(default_factory=list)
    has_nvme: bool = False
    has_wifi: bool = False
    uefi: bool = False

    def cache_key(self) -> str:
        """Stable hash of build-relevant fields; used to look up binary caches."""
        core = {k: v for k, v in asdict(self).items()
                if k in ("arch", "march", "cpu_flags", "video_cards")}
        return hashlib.sha256(json.dumps(core, sort_keys=True).encode()).hexdigest()[:16]


def parse_cpuinfo(text: str):
    model = re.search(r"model name\s*:\s*(.+)", text)
    flags = re.search(r"^flags\s*:\s*(.+)$", text, re.M)
    flagset = set(flags.group(1).split()) if flags else set()
    return (model.group(1).strip() if model else "unknown",
            sorted(f for f in CPU_FLAG_MAP if f in flagset))


def parse_lspci(text: str):
    cards = set()
    has_nvme = False
    has_wifi = False
    for line in text.splitlines():
        if re.search(r"VGA|3D|Display", line):
            m = re.search(r"\[([0-9a-f]{4}):[0-9a-f]{4}\]", line)
            if m and m.group(1) in GPU_VENDORS:
                cards.update(GPU_VENDORS[m.group(1)].split())
        if re.search(r"Non-Volatile memory|NVMe", line, re.I):
            has_nvme = True
        if re.search(r"Network controller|Wireless|Wi-Fi", line, re.I):
            has_wifi = True
    return sorted(cards), has_nvme, has_wifi


def detect_march() -> str:
    try:
        out = subprocess.run(["gcc", "-march=native", "-Q", "--help=target"],
                             capture_output=True, text=True, timeout=20).stdout
        m = re.search(r"-march=\s+(\S+)", out)
        if m and m.group(1) != "native":
            return m.group(1)
    except (OSError, subprocess.SubprocessError):
        pass
    return "x86-64"


def detect() -> Profile:
    def read(p):
        try:
            return open(p).read()
        except OSError:
            return ""
    model, flags = parse_cpuinfo(read("/proc/cpuinfo"))
    mem = re.search(r"MemTotal:\s+(\d+)", read("/proc/meminfo"))
    try:
        lspci = subprocess.run(["lspci", "-nn"], capture_output=True, text=True, timeout=10).stdout
    except (OSError, subprocess.SubprocessError):
        lspci = ""
    cards, has_nvme, has_wifi = parse_lspci(lspci)
    return Profile(cpu_model=model, march=detect_march(), cpu_flags=flags,
                   cores=os.cpu_count() or 1,
                   mem_mb=int(mem.group(1)) // 1024 if mem else 0,
                   video_cards=cards or ["fbdev"],
                   has_nvme=has_nvme,
                   has_wifi=has_wifi,
                   uefi=os.path.isdir("/sys/firmware/efi"))


def make_conf(p: Profile) -> str:
    # Keep jobs bounded by RAM (~2GB per job) so compiles don't OOM.
    jobs = max(1, min(p.cores, max(1, p.mem_mb // 2048)))
    return f"""# Generated by zeros-detect (profile {p.cache_key()}) - do not edit by hand
COMMON_FLAGS="-march={p.march} -O2 -pipe"
CFLAGS="${{COMMON_FLAGS}}"
CXXFLAGS="${{COMMON_FLAGS}}"
MAKEOPTS="-j{jobs}"
EMERGE_DEFAULT_OPTS="--jobs={max(1, jobs // 2)} --load-average={p.cores}"
CPU_FLAGS_X86="{' '.join(p.cpu_flags)}"
VIDEO_CARDS="{' '.join(p.video_cards)}"
USE="wayland -systemd -gnome -kde elogind btrfs wifi networkmanager"
FEATURES="getbinpkg binpkg-request-signature"
"""


if __name__ == "__main__":
    import sys
    prof = detect()
    if "--make-conf" in sys.argv:
        print(make_conf(prof))
    else:
        print(json.dumps({**asdict(prof), "cache_key": prof.cache_key()}, indent=2))
